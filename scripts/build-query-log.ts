#!/usr/bin/env -S npx tsx
/**
 * Writes the "bench-validation" half of data/query-log.json's predicted-
 * vs-observed log: every real recorded trial in data/trials.json, checked
 * leave-one-out against lib/validation.ts. See that file's header for why
 * leave-one-out, not a live writer, and not a circular check.
 *
 * Run after adding or editing a trial in data/trials.json:
 *   npx tsx scripts/build-query-log.ts
 *
 * This is a BATCH step, not something the live app calls - this project's
 * standing architecture decision is that a serverless app has nothing
 * durable to write to (the same reasoning data/field-observations.json's
 * lack of a live writer follows). Re-run and commit the result by hand.
 *
 * "site-run" entries (a real screened site, not a bench trial) are a
 * distinct kind this file preserves rather than overwrites - there are
 * none yet, since that needs a real on-site trial recorded against a
 * siteId/waterbodyId (see HANDOFF.md's "What would most improve this").
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadHydrocyclones, loadMembranes, loadTrials } from "../lib/data";
import { buildBenchValidationEntries } from "../lib/validation";

const QUERY_LOG_PATH = join(process.cwd(), "data", "query-log.json");

function main() {
  const trials = loadTrials();
  const membranes = loadMembranes();
  const hydrocyclones = loadHydrocyclones();

  const benchEntries = buildBenchValidationEntries(trials, membranes, hydrocyclones);

  const existing = JSON.parse(readFileSync(QUERY_LOG_PATH, "utf8")) as { _README: string[]; entries: unknown[] };
  const nonBench = existing.entries.filter((e) => (e as { kind?: string }).kind !== "bench-validation");

  const withinBaseline = benchEntries.filter((e) => e.baselineWithinPredictedRange).length;
  const withinUplift = benchEntries.filter((e) => e.upliftWithinPredictedRange).length;

  const out = {
    _README: [
      "Every screening run, plus a leave-one-out validation check against",
      "every real recorded bench trial in data/trials.json. See lib/validation.ts.",
      "",
      "Two kinds of entry:",
      "  bench-validation   a real bench trial, checked against a prediction",
      "                      made WITHOUT using that trial's own data (see",
      "                      lib/validation.ts's header for why leave-one-out).",
      "                      Regenerated by scripts/build-query-log.ts whenever",
      "                      data/trials.json changes - do not hand-edit these.",
      "  site-run            a real screened site. Keyed on siteId + waterbodyId,",
      "                      NOT the text the user typed - two spellings of the",
      "                      same burn are the same site. None exist yet: this",
      "                      needs a real on-site trial recorded against a",
      "                      siteId/waterbodyId (see HANDOFF.md).",
      "",
      "This is the prototype's whole persistence layer. There is no database -",
      "this file is written by a batch script, never by the live app.",
      "",
      `Last generated by scripts/build-query-log.ts: ${benchEntries.length} bench trials checked, ` +
        `${withinBaseline}/${benchEntries.length} baseline predictions contained the real measured ` +
        `volume, ${withinUplift}/${benchEntries.length} uplift predictions contained the real ` +
        "measured ratio. See each entry's own fields for which ones didn't, and why - a miss here " +
        "is exactly the signal this validation loop exists to surface, not a bug to hide.",
    ],
    entries: [...nonBench, ...benchEntries],
  };

  writeFileSync(QUERY_LOG_PATH, JSON.stringify(out, null, 2) + "\n");
  console.log(`Wrote ${benchEntries.length} bench-validation entries + ${nonBench.length} preserved entries to ${QUERY_LOG_PATH}`);
  console.log(`Baseline predictions contained the real reading: ${withinBaseline}/${benchEntries.length}`);
  console.log(`Uplift predictions contained the real reading: ${withinUplift}/${benchEntries.length}`);
}

main();
