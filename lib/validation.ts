import type { Hydrocyclone, Membrane, Trial } from "./data";
import {
  calibrateBaselines,
  foulingLoadForMembrane,
  predictBaselineVolume,
  psdFromMeasuredD20D50D90,
  type VolumeRange,
} from "./baseline";
import { assessUplift, type MultiplierRange } from "./assessment";
import { measuredVolumeRatio } from "./trials";

/**
 * BLOCK 6, rebuild phase 9 continued - the other half of the validation
 * loop data/validated-studies.json started (checking this tool's
 * assumptions against published literature). This half checks the tool's
 * OWN predictions against its OWN real bench trials - the thing the
 * 2026-09-27 outside critique's point 4 specifically asked for.
 *
 * The honest way to do this is LEAVE-ONE-OUT: predicting a trial using a
 * calibration that trial itself helped build is circular and would always
 * look better than the model actually is. Every entry here is predicted
 * from the OTHER recorded trials only, then checked against what this one
 * trial actually measured. This is the real test of whether the general
 * bench-trial calibration (lib/baseline.ts) generalises AT ALL, which is
 * exactly what "no validation" was pointing at.
 *
 * The per-hydrocyclone UPLIFT is a different case: lib/assessment.ts's
 * assessUplift never reads data/trials.json at all - it is a pure function
 * of the feed PSD and the hydrocyclone's (guessed) grade-efficiency curve.
 * So there is no leave-one-out needed there; "predicted" just means
 * "what the model says for this trial's own measured feed PSD," checked
 * against the real measured volumeAfterMl/volumeBeforeMl ratio.
 *
 * This is deliberately a BATCH function, not something the live app calls.
 * Per this project's standing architecture decision (no live writer for
 * data/query-log.json or data/field-observations.json - a serverless app
 * has nothing durable to write to), results are generated by
 * scripts/build-query-log.ts and committed, not computed on every request.
 */

export interface BenchValidationEntry {
  kind: "bench-validation";
  trialId: string;
  membraneId: string;
  hydrocycloneId: string | null;
  /** Leave-one-out: calibrated from every OTHER recorded trial at this pore size, never this one. */
  predictedBaselineMl: VolumeRange | null;
  observedBaselineMl: number | null;
  /** Null when predictedBaselineMl is null - insufficient data to check, not a failed check. */
  baselineWithinPredictedRange: boolean | null;
  predictedUpliftMultiplier: MultiplierRange | null;
  observedUpliftMultiplier: number | null;
  upliftWithinPredictedRange: boolean | null;
  note: string;
}

function within(value: number, range: { lowMl?: number; highMl?: number; low?: number; high?: number }): boolean {
  const low = range.lowMl ?? range.low ?? -Infinity;
  const high = range.highMl ?? range.high ?? Infinity;
  return value >= low && value <= high;
}

/**
 * One trial's leave-one-out baseline prediction + uplift prediction,
 * checked against what it actually measured. Returns null for a trial
 * that cannot be validated at all: not recorded, no measured feed PSD, or
 * no membrane/hydrocyclone on record matching it - "insufficient data" to
 * even attempt a check, not a negative result.
 */
export function validateTrial(
  trial: Trial,
  allTrials: Trial[],
  membranes: Membrane[],
  hydrocyclones: Hydrocyclone[],
): BenchValidationEntry | null {
  if (trial.status !== "recorded") return null;
  if (!trial.feed?.psd || !(trial.volumeBeforeMl! > 0)) return null;
  const poreSizeUm = trial.filter?.poreSizeUm;
  const membrane = membranes.find((m) => m.poreSizeUm === poreSizeUm);
  if (!membrane) return null;

  const trialPsd = psdFromMeasuredD20D50D90(trial.feed.psd.d20Um, trial.feed.psd.d50Um, trial.feed.psd.d90Um);

  // Leave-one-out: every OTHER recorded trial, never this one.
  const otherTrials = allTrials.filter((t) => t.id !== trial.id);
  const membranesByPoreSize = new Map(membranes.map((m) => [m.poreSizeUm, m]));
  const calibrations = calibrateBaselines(otherTrials, membranesByPoreSize);
  const calibration = calibrations.find((c) => c.poreSizeUm === poreSizeUm);
  const { foulingLoad: alpha } = foulingLoadForMembrane(trialPsd, membrane);
  const predictedBaselineMl = predictBaselineVolume(calibration, alpha, trial.feed.untreatedConcentrationMgL ?? undefined);
  const observedBaselineMl = trial.volumeBeforeMl!;
  const baselineWithinPredictedRange = predictedBaselineMl ? within(observedBaselineMl, predictedBaselineMl) : null;

  const hydrocyclone = hydrocyclones.find((h) => h.id === trial.hydrocycloneId);
  const observedUpliftMultiplier = measuredVolumeRatio(trial);
  let predictedUpliftMultiplier: MultiplierRange | null = null;
  let upliftWithinPredictedRange: boolean | null = null;
  if (hydrocyclone && observedUpliftMultiplier !== null) {
    predictedUpliftMultiplier = assessUplift(trialPsd, membrane, hydrocyclone).multiplier;
    upliftWithinPredictedRange = within(observedUpliftMultiplier, predictedUpliftMultiplier);
  }

  const note = !hydrocyclone
    ? `Hydrocyclone "${trial.hydrocycloneId}" is not in data/hydrocyclones.json, so the uplift side of this trial cannot be checked.`
    : !calibration
      ? `No OTHER recorded trial calibrates a ${poreSizeUm} µm filter, so the baseline side of this trial cannot be checked without it contributing to its own prediction - left as insufficient data rather than a circular check.`
      : "Baseline predicted leave-one-out (calibrated from every other recorded trial, never this one); uplift predicted from this trial's own measured feed PSD and the hydrocyclone's grade-efficiency curve (which never reads trial data at all).";

  return {
    kind: "bench-validation",
    trialId: trial.id,
    membraneId: membrane.id,
    hydrocycloneId: trial.hydrocycloneId,
    predictedBaselineMl,
    observedBaselineMl,
    baselineWithinPredictedRange,
    predictedUpliftMultiplier,
    observedUpliftMultiplier,
    upliftWithinPredictedRange,
    note,
  };
}

/** Every recorded, checkable trial in one go - what scripts/build-query-log.ts writes to data/query-log.json. */
export function buildBenchValidationEntries(
  trials: Trial[],
  membranes: Membrane[],
  hydrocyclones: Hydrocyclone[],
): BenchValidationEntry[] {
  return trials
    .map((t) => validateTrial(t, trials, membranes, hydrocyclones))
    .filter((e): e is BenchValidationEntry => e !== null);
}
